'use strict';
const {contextBridge, ipcRenderer, webUtils} = require('electron');
contextBridge.exposeInMainWorld('eoDesktop', Object.freeze({
  aiSettings: () => ipcRenderer.invoke('eo:ai-settings'),
  aiConfigure: value => ipcRenderer.invoke('eo:ai-configure', value),
  aiRequest: (id, body) => ipcRenderer.invoke('eo:ai-request', id, body),
  aiCancel: id => ipcRenderer.invoke('eo:ai-cancel', id),
  author: () => ipcRenderer.invoke('eo:author'),
  authorSave: value => ipcRenderer.invoke('eo:author-save', value),
  about: () => ipcRenderer.invoke('eo:about'),
  quit: () => ipcRenderer.invoke('eo:quit'),
  help: () => ipcRenderer.invoke('eo:help'),
  locale: () => ipcRenderer.invoke('eo:locale'),
  captureLocale: language => ipcRenderer.invoke('eo:capture-locale', language),
  passwordLock: token => ipcRenderer.invoke('eo:password-lock', token),
  recoveryFailure: () => ipcRenderer.invoke('eo:recovery-failure'),
  recoveryOptions: () => ipcRenderer.invoke('eo:recovery-options'),
  recoverySettings: value => ipcRenderer.invoke('eo:recovery-settings', value),
  recoveryList: () => ipcRenderer.invoke('eo:recovery-list'),
  recoverySave: (token, version, bytes) => ipcRenderer.invoke('eo:recovery-save', token, version, bytes),
  recoveryClear: token => ipcRenderer.invoke('eo:recovery-clear', token),
  recoveryRemove: id => ipcRenderer.invoke('eo:recovery-remove', id),
  recoveryRestore: id => ipcRenderer.invoke('eo:recovery-restore', id),
  home: () => ipcRenderer.invoke('eo:home'),
  returnHome: () => ipcRenderer.invoke('eo:return-home'),
  template: id => ipcRenderer.invoke('eo:template', id),
  closeSaved: () => ipcRenderer.invoke('eo:closed-saved'),
  initial: () => ipcRenderer.invoke('eo:initial'),
  choose: () => ipcRenderer.invoke('eo:open'),
  recent: id => ipcRenderer.invoke('eo:recent', id),
  recents: () => ipcRenderer.invoke('eo:recents'),
  create: format => ipcRenderer.invoke('eo:new', format),
  drop: file => ipcRenderer.invoke('eo:drop', webUtils.getPathForFile(file)),
  rename: (token, name) => ipcRenderer.invoke('eo:rename', token, name),
  copySaveDiagnostics: () => ipcRenderer.invoke('eo:copy-save-diagnostics'),
  cancelWrite: (token, operationId) => ipcRenderer.invoke('eo:write-cancel', token, operationId),
  save: (token, bytes, as, protection, operationId, ticket) => ipcRenderer.invoke('eo:save', token, bytes, !!as, protection, operationId, ticket),
  savedOpen: id => ipcRenderer.invoke('eo:saved-open', id),
  savedShow: id => ipcRenderer.invoke('eo:saved-show', id),
  exportFormats: token => ipcRenderer.invoke('eo:export-formats', token),
  export: (token, bytes, format, protection, operationId, ticket) => ipcRenderer.invoke('eo:export', token, bytes, format, protection, operationId, ticket),
  pdf: (token, bytes, print, plainCopy, operationId, ticket) => ipcRenderer.invoke('eo:pdf', token, bytes, !!print, plainCopy, operationId, ticket),
  saveAsInfo: token => ipcRenderer.invoke('eo:save-as-info', token),
  saveAsChoose: (token, format, pdfCopy) => ipcRenderer.invoke('eo:save-as-choose', token, format, pdfCopy),
  saveAsCancel: token => ipcRenderer.invoke('eo:save-as-cancel', token),
  state: (token, dirty) => ipcRenderer.invoke('eo:state', token, !!dirty),
  fontChoice: () => ipcRenderer.invoke('eo:font-choice'),
  fontDismiss: () => ipcRenderer.invoke('eo:font-dismiss'),
  fontDisable: () => ipcRenderer.invoke('eo:font-disable'),
  fontPermission: () => ipcRenderer.invoke('eo:font-permission'),
  fontConsent: () => ipcRenderer.invoke('eo:font-consent'),
  fontIndex: readyOnly => ipcRenderer.invoke('eo:font-index',readyOnly),
  fonts: () => ipcRenderer.invoke('eo:fonts'),
  font: id => ipcRenderer.invoke('eo:font', id),
  onOperationStage: callback => { const listener = (_event, value) => callback(value); ipcRenderer.on('eo:operation-stage', listener); return () => ipcRenderer.removeListener('eo:operation-stage', listener); },
  onAction: callback => { const listener = (_event, action) => callback(action); ipcRenderer.on('eo:action', listener); return () => ipcRenderer.removeListener('eo:action', listener); }
}));

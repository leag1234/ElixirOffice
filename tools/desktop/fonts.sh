set -euo pipefail
ROOT="$(cd "$(dirname "$0")/../.." && pwd)"
: "${FONT_TOOL_IMAGE:?immutable image ID containing the font generator}"
: "${FONT_TOOL_ROOT:?documentserver directory inside the pinned font-tool image}"
: "${CORE_FONTS:?licensed upstream free-font checkout}"
: "${FONT_PACK:?generated licensed font pack}"
: "${FONT_OUTPUT:?fresh output folder}"
[ ! -e "$FONT_OUTPUT" ] || { echo "Choose a fresh font output directory" >&2; exit 1; }
case "$FONT_TOOL_IMAGE" in sha256:*) ;; *) echo "Pin a sha256 image ID" >&2; exit 1;; esac
FONT_SET="${FONT_SET:-standard}"
case "$FONT_SET" in standard|full) ;; *) echo "FONT_SET must be standard or full" >&2; exit 1;; esac
mkdir -p "$FONT_OUTPUT/fonts" "$FONT_OUTPUT/Images"
if [ "$FONT_SET" = standard ]; then
 python3 "$ROOT/tools/desktop/font-inputs.py" "$CORE_FONTS" "$FONT_PACK" "$FONT_OUTPUT/inputs"
 CORE_FONTS="$FONT_OUTPUT/inputs/core"
 FONT_PACK="$FONT_OUTPUT/inputs/pack"
fi
printf '%s\n' "$FONT_SET" > "$FONT_OUTPUT/font-set.txt"
docker run --rm --name "eo-desktop-A-fonts-$$" --network none --user "$(id -u):$(id -g)" --entrypoint /bin/sh \
 -e FONT_TOOL_ROOT="$FONT_TOOL_ROOT" -v "$CORE_FONTS:/input:ro" -v "$FONT_PACK:/pack:ro" -v "$FONT_OUTPUT:/out" "$FONT_TOOL_IMAGE" -c '
 set -e
 export LD_LIBRARY_PATH=$FONT_TOOL_ROOT/server/FileConverter/bin
 "$FONT_TOOL_ROOT/server/tools/allfontsgen" --input=/input --input=/pack --allfonts-web=/out/AllFonts.js --allfonts=/out/AllFonts-native.js --images=/out/Images --selection=/out/font_selection.bin --output-web=/out/fonts --use-system=false --use-system-user-fonts=false'

python3 - "$FONT_OUTPUT" "$FONT_SET" <<'PYVERIFY'
import sys
from pathlib import Path
output=Path(sys.argv[1])
for name in ("AllFonts.js","AllFonts-native.js","font_selection.bin"):
    assert (output/name).stat().st_size>0, "Missing generated font metadata"
assert any(p.is_file() and p.stat().st_size>0 for p in (output/"fonts").iterdir()), "Empty font output"
if sys.argv[2]=="standard":
    metadata=(output/"AllFonts.js").read_text()
    for name in ("Liberation Sans","Carlito","Caladea","Marelle","Selawik","Elixir Symbols"):
        assert name in metadata, "Missing standard family: "+name
print("PASS",sys.argv[2],"font metadata and generated bytes")
PYVERIFY

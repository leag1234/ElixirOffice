function icns(pngs){ // pngs: {pixels:Buffer}; PNG-based entries, no legacy ARGB small types
 const map=[['ic07',128],['ic08',256],['ic09',512],['ic10',1024],['ic11',32],['ic12',64],['ic13',256],['ic14',512]];
 const parts=map.map(([t,px])=>{const h=Buffer.alloc(8);h.write(t);h.writeUInt32BE(pngs[px].length+8,4);return Buffer.concat([h,pngs[px]])});
 const h=Buffer.alloc(8);h.write('icns');h.writeUInt32BE(8+parts.reduce((n,b)=>n+b.length,0),4);return Buffer.concat([h,...parts]);
}
function ico(pngs){const sizes=[16,24,32,48,64,256];const head=Buffer.alloc(6);head.writeUInt16LE(1,2);head.writeUInt16LE(sizes.length,4);
 let off=6+16*sizes.length;const dir=[],data=[];
 for(const s of sizes){const d=Buffer.alloc(16);d[0]=s===256?0:s;d[1]=s===256?0:s;d.writeUInt16LE(1,4);d.writeUInt16LE(32,6);d.writeUInt32LE(pngs[s].length,8);d.writeUInt32LE(off,12);off+=pngs[s].length;dir.push(d);data.push(pngs[s])}
 return Buffer.concat([head,...dir,...data]);}

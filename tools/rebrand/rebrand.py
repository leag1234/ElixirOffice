def visible_findings(root, repo, name, findings):
    scopes = [g for r, g in VISIBLE if r == name]
    if not scopes:
        return
    prefix = (name + "/") if name != "<product>" else "<product>/"
    for f in tracked(repo):
        if excluded(f) or not match_any(f, scopes[0]) or match_any(f, VISIBLE_SKIP):
            continue
        text = read_text(os.path.join(repo, f))
        if text is None or not _V.search(text):
            continue
        head = header_lines(text.split("\n"))
        for i, line in enumerate(text.split("\n")):
            if i in head or not _V.search(line):
                continue
            for seg in segments(line):
                if not _V.search(seg) or KEEP_STRICT.search(seg):
                    continue
                for globs, rx, _why in VISIBLE_ALLOW:
                    if match_any(f, globs):
                        seg = rx.sub("", seg)
                if _V.search(seg):
                    findings.append((prefix + f, i + 1, "(visible) " + line.strip()[:150]))


# ---------------------------------------------------------------- helpers
def git(repo, *args, check=True):
    return subprocess.run(["git", "-C", repo, *args], check=check,
                          capture_output=True, text=True).stdout


def repos(root):
    """root and all its submodules (recursive), deepest first."""
    out = [root]
    paths = git(root, "submodule", "foreach", "--quiet", "--recursive",
                "echo $displaypath", check=False).split()
    for p in paths:
        full = os.path.join(root, p)
        if os.path.exists(os.path.join(full, ".git")):
            out.append(full)
    return sorted(out, key=lambda p: -p.count(os.sep))


def match_any(path, globs):
    return any(fnmatch.fnmatch(path, g) for g in globs)


def excluded(path):
    for g, why in EXCLUDE_FILES:
        if fnmatch.fnmatch(path, g):
            return why
    return None


def tracked(repo):
    files = git(repo, "ls-files", "-z", "--", ".").split("\0")
    subs = set(git(repo, "submodule", "--quiet", "foreach", "echo $sm_path", check=False).split())
    return [f for f in files if f and f not in subs]


def read_text(full):
    try:
        with open(full, "rb") as fh:
            data = fh.read()
    except (IsADirectoryError, FileNotFoundError):
        return None
    if b"\0" in data[:8192]:
        return None
    return data.decode("utf-8", "surrogateescape")


def header_lines(lines):
    """Indexes of the leading comment block when it is a license header."""
    block, in_c = [], False
    for i, line in enumerate(lines[:150]):
        s = line.strip()
        if i == 0 and s.startswith("#!"):
            continue
        if in_c:
            block.append(i)
            if "*/" in s or "-->" in s:
                in_c = False
            continue
        if not block and s == "":
            continue
        if s.startswith("/*") or s.startswith("<!--"):
            block.append(i)
            in_c = not ("*/" in s[2:] or "-->" in s[4:])
            continue
        if s.startswith(("//", "*", "#", "--", ";")) and not s.startswith("#include"):
            block.append(i)
            continue
        break
    if any(HEADER_HINT.search(lines[i]) for i in block):
        return set(block)
    return set()


class Mask:
    """Hide protected spans while rules run, restore them afterwards."""
    def __init__(self, line, regexes):
        self.saved = []
        for rx in regexes:
            line = rx.sub(self._hide, line)
        self.line = line

    def _hide(self, m):
        self.saved.append(m.group(0))
        return "\x00%d\x00" % (len(self.saved) - 1)

    def restore(self, line):
        return re.sub(r"\x00(\d+)\x00", lambda m: self.saved[int(m.group(1))], line)


def rules_for(repo_name, path):
    rules = list(EO_RULES)
    for r, globs, rx, rep in OO_RULES + PHRASE_RULES:
        if r == repo_name and match_any(path, globs):
            rules.append((rx, rep))
    return rules


def candidate(repo_name, path, text):
    """True when the file may hold something to rewrite (cheap pre-filter)."""
    if EO_ANY.search(text) or "nlyoffice" in text.lower():
        return True
    return any(r == repo_name and match_any(path, globs) and rx.search(text)
               for r, globs, rx, _ in PHRASE_RULES)


def protects_for(repo_name, path):
    if repo_name == PRODUCT:
        return list(PRODUCT_PROTECT) + (list(README_COMPARISON) if path == "README.md" else [])
    return [rx for g, rx, _ in PROTECT if repo_name == "" and fnmatch.fnmatch(path, g)]


# Long lines (minified JSON, help search indexes) hold many sentences: the
# copyright/lineage exception then applies per sentence, not to the whole line.
SEGMENT = re.compile(r"(?<=\. )|(?<=</p>)|(?<=\",)|(?<=\\n)")


def segments(line):
    return SEGMENT.split(line) if len(line) > 300 else [line]


def rewrite(seg, rules, protects, strict=False):
    if (KEEP_STRICT if strict else KEEP_LINE).search(seg):
        return seg
    m = Mask(seg, protects)
    new = m.line
    for rx, rep in rules:
        new = rx.sub(rep, new)
    return m.restore(new)


def process_file(repo_name, path, text, apply):
    """Returns (new_text, findings) findings = [(lineno, line)] still matching."""
    lines = text.split("\n")
    head = header_lines(lines)
    rules = rules_for(repo_name, path)
    protects = protects_for(repo_name, path)
    changed, findings = False, []
    for i, line in enumerate(lines):
        if i in head:
            continue
        new = "".join(rewrite(seg, rules, protects, repo_name == PRODUCT or "/resources/help/" in path)
                      for seg in segments(line))
        if new != line:
            if apply:
                lines[i] = new
                changed = True
            else:
                findings.append((i + 1, line))
    return ("\n".join(lines) if changed else None), findings


def repo_name_of(root, repo):
    rel = os.path.relpath(repo, root)
    return "" if rel == "." else rel


# Paths renamed or removed. The upstream web-apps theme is removed: ours lives in
# the product repository (branding/web-apps/theme/elixiroffice) and is injected by
# `make theme` (dev) and the brand-icons bake target (images).
PATH_DELETE = [("web-apps", "theme/" + _E + _O)]


def path_target(p):
    new = p
    for rx, rep in EO_RULES:
        new = rx.sub(rep, new)
    return new


# ---------------------------------------------------------------- commands
def rename_repo(root, repo, name, do_commit=False, branch="elixir/rebrand"):
    n = 0
    for r, p in PATH_DELETE:
        if r == name and os.path.exists(os.path.join(repo, p)):
            git(repo, "rm", "-r", "-q", "--", p)
            n += 1
    for f in tracked(repo):
        if excluded(f):
            continue
        t = path_target(f)
        if t != f and os.path.exists(os.path.join(repo, f)):
            os.makedirs(os.path.dirname(os.path.join(repo, t)) or ".", exist_ok=True)
            git(repo, "mv", "--", f, t)
            n += 1
    for f in tracked(repo):
        if excluded(f):
            continue
        full = os.path.join(repo, f)
        text = read_text(full)
        if text is None or not candidate(name, f, text):
            continue
        new, _ = process_file(name, f, text, True)
        if new is not None:
            st = os.stat(full)
            with open(full, "w", encoding="utf-8", errors="surrogateescape", newline="") as fh:
                fh.write(new)
            os.chmod(full, st.st_mode)
            n += 1
    print("%-60s %d file(s) changed" % (name if name != PRODUCT else "<product>", n))
    if do_commit:
        commit(repo, branch)
    return n


def cmd_rename(a):
    total = 0
    if a.ds:
        root = os.path.abspath(a.ds)
        for repo in repos(root):
            total += rename_repo(root, repo, repo_name_of(root, repo), a.commit, a.branch)
    if a.product:
        prod = os.path.abspath(a.product)
        total += rename_repo(prod, prod, PRODUCT)  # committed by hand (not generated history)
    print("rename: %d file(s) changed" % total)


# History rewrite API (git filter-repo callbacks): same rules as the working tree.
def transform_path(path):
    return path if excluded(path) else path_target(path)


def transform_blob(path, data):
    """bytes -> bytes for the file `path` (new or old path, both give the same result)."""
    if excluded(path) or b"\0" in data[:8192]:
        return data
    text = data.decode("utf-8", "surrogateescape")
    if not (EO_ANY.search(text) or "nlyoffice" in text.lower()):
        return data
    new, _ = process_file(PRODUCT, path, text, True)
    return data if new is None else new.encode("utf-8", "surrogateescape")


def transform_message(msg):
    out = []
    for line in msg.split("\n"):
        out.append("".join(rewrite(seg, list(EO_RULES), list(PRODUCT_PROTECT), True) for seg in segments(line)))
    return "\n".join(out)


def commit(repo, branch):
    git(repo, "add", "-u")
    if not git(repo, "status", "--porcelain"):
        return
    if git(repo, "symbolic-ref", "-q", "HEAD", check=False).strip() == "":
        git(repo, "checkout", "-q", "-B", branch)
    subprocess.run(["git", "-C", repo, "commit", "-q", "-m", COMMIT_MSG, "-m", COMMIT_BODY], check=True)
    print("   committed %s" % git(repo, "rev-parse", "--short", "HEAD").strip())


def scan_repo(root, repo, findings, name=None):
    if name is None:
        name = repo_name_of(root, repo)
    prefix = (name + "/") if name and name != PRODUCT else ("<product>/" if name == PRODUCT else "")
    for r, p in PATH_DELETE:
        if r == name and os.path.exists(os.path.join(repo, p)):
            findings.append((prefix + p, 0, "(path) should be removed"))
    for f in tracked(repo):
        if excluded(f):
            continue
        if path_target(f) != f:
            findings.append((prefix + f, 0, "(path)"))
        text = read_text(os.path.join(repo, f))
        if text is None:
            continue
        if not candidate(name, f, text):
            continue
        _, fl = process_file(name, f, text, False)
        for ln, line in fl:
            findings.append((prefix + f, ln, line.strip()[:160]))


def scan_product(prod, findings):
    scan_repo(prod, prod, findings, PRODUCT)


def cmd_check(a):
    findings = []
    if a.ds:
        root = os.path.abspath(a.ds)
        for repo in repos(root):
            scan_repo(root, repo, findings)
            visible_findings(root, repo, repo_name_of(root, repo), findings)
    if a.product:
        scan_product(os.path.abspath(a.product), findings)
        prod = os.path.abspath(a.product)
        visible_findings(prod, prod, "<product>", findings)
    for f, ln, line in sorted(findings):
        print("%s:%d: %s" % (f, ln, line))
    print("check: %d finding(s)" % len(findings), file=sys.stderr)
    sys.exit(1 if findings else 0)


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    sp = ap.add_subparsers(dest="cmd", required=True)
    r = sp.add_parser("rename")
    r.add_argument("ds")
    r.add_argument("--product", help="also rewrite the ElixirOffice repository (docs, patches, baselines included)")
    r.add_argument("--commit", action="store_true", help="commit in every changed repository (deepest first)")
    r.add_argument("--branch", default="elixir/rebrand", help="branch created when a submodule is on a detached HEAD")
    c = sp.add_parser("check")
    c.add_argument("ds")
    c.add_argument("--product", help="also check the ElixirOffice repository (everything tracked)")
    for nm in ("rename-product", "check-product"):
        sp.add_parser(nm).add_argument("dir")
    a = ap.parse_args()
    if a.cmd == "rename-product":
        a.ds, a.product, a.commit, a.branch = None, a.dir, False, ""
        return cmd_rename(a)
    if a.cmd == "check-product":
        a.ds, a.product = None, a.dir
        return cmd_check(a)
    {"rename": cmd_rename, "check": cmd_check}[a.cmd](a)


if __name__ == "__main__":
    main()

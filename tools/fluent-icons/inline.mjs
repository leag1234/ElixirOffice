// Generates the inline Fluent UI System Icons (MIT,
// https://github.com/microsoft/fluentui-system-icons) used by the ElixirOffice
// window chrome (backstage, title bar, navigation pane): a small AMD module that
// maps an icon name to the <path> markup of its 20 px and 24 px "regular"
// variants, drawn with currentColor so the theme colours them.
//
// Usage:
//   node tools/fluent-icons/inline.mjs <package/icons> <web-apps>/apps/documenteditor/main/app/elixir-chrome/Icons.js
//   node tools/fluent-icons/inline.mjs <package/icons> <web-apps>/apps/common/main/lib/elixir-chrome/Icons.js (shared by the editors)
//
// The list of icons is inline.json (name -> Fluent base name).
import fs from 'fs';
import path from 'path';
import { fileURLToPath } from 'url';

const here = path.dirname(fileURLToPath(import.meta.url));
const [src, out] = process.argv.slice(2);
if (!src || !out || !fs.existsSync(src)) {
  console.error('usage: node inline.mjs <@fluentui/svg-icons package/icons dir> <out Icons.js>');
  process.exit(1);
}
const list = JSON.parse(fs.readFileSync(path.join(here, 'inline.json'), 'utf8')).icons;
const icons = {};
const missing = [];
for (const [name, fluent] of Object.entries(list)) {
  icons[name] = {};
  for (const size of [20, 24]) {
    const file = path.join(src, `${fluent}_${size}_regular.svg`);
    if (!fs.existsSync(file)) { missing.push(`${fluent}_${size}`); continue; }
    const svg = fs.readFileSync(file, 'utf8');
    const body = svg.replace(/^[\s\S]*?<svg[^>]*>/, '').replace(/<\/svg>\s*$/, '')
      .replace(/\s(fill)="[^"]*"/g, '');
    icons[name][size] = body;
  }
}
if (missing.length) { console.error('missing: ' + missing.join(', ')); process.exit(1); }

const js = `/*
 * ElixirOffice window chrome: inline Fluent UI System Icons.
 * Generated by tools/fluent-icons/inline.mjs (ElixirOffice repository), do not edit.
 * Icons: Fluent UI System Icons, (c) Microsoft Corporation, MIT License
 * (https://github.com/microsoft/fluentui-system-icons/blob/main/LICENSE).
 */
define([], function () {
    'use strict';
    var P = ${JSON.stringify(icons, null, 0)};
    // ElixirChrome.icon('print', 20, 'cls') -> '<svg ...>'
    window.ElixirChromeIcons = {
        has: function (name) { return !!P[name]; },
        svg: function (name, size, cls) {
            size = size === 24 ? 24 : 20;
            var p = P[name] && (P[name][size] || P[name][size === 24 ? 20 : 24]);
            if (!p) return '';
            return '<svg class="elx-icon' + (cls ? ' ' + cls : '') + '" width="' + size + '" height="' + size +
                '" viewBox="0 0 ' + size + ' ' + size + '" fill="currentColor" aria-hidden="true" focusable="false">' + p + '</svg>';
        }
    };
    return window.ElixirChromeIcons;
});
`;
fs.writeFileSync(out, js);
console.log(`${Object.keys(icons).length} icons -> ${out}`);
